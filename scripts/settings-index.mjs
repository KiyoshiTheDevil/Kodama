// Builds src/settings/search-index.js: every settings row and section with the tab and section
// it lives in, for the title bar's search while the settings are open. Read from the source
// rather than kept by hand, so a new row is findable without anyone remembering to add it.
// Runs before every `npm run build`; run it by hand after adding rows during development:
//   node scripts/settings-index.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

// label={t("key")} / label={t("key") || "…"} / label="Literal"; the first t("…") of a description.
const labelOf = (chunk) => {
  const m = chunk.match(/\blabel=\{t\("([^"]+)"\)/) || chunk.match(/\blabel="([^"]+)"/);
  return m ? { k: m[1], lit: !chunk.match(/\blabel=\{t\(/) } : null;
};
const descOf = (chunk) => chunk.match(/\bdescription=\{[^}]*?t\("([^"]+)"\)/)?.[1] || null;

// Rows inside one stretch of source, cut at each <SettingRow so a row never borrows its
// neighbour's label.
function rowsIn(text) {
  const out = [];
  const parts = text.split("<SettingRow").slice(1);
  for (const p of parts) {
    const chunk = p.slice(0, 600);
    const l = labelOf(chunk);
    if (!l) continue;
    out.push({ k: l.k, lit: l.lit || undefined, d: descOf(chunk) || undefined });
  }
  return out;
}

const entries = [];
const add = (e) => entries.push(Object.fromEntries(Object.entries(e).filter(([, v]) => v !== undefined && v !== null)));

// ── panel.jsx: tabs, section anchors, section labels, rows, and row components ──
const panel = read("src/settings/panel.jsx");
const lines = panel.split("\n");

// Helper components defined in the file (LastfmRow, AudioOutputRow, …): their rows count
// wherever the component is used.
const components = {};
{
  // `export function` too: it ends the helper before it, or that helper would swallow the panel.
  const re = /^(?:export )?function (\w+)\(/gm;
  const marks = [...panel.matchAll(re)].map((m) => ({ name: m[1], at: m.index }));
  marks.forEach((m, i) => {
    const body = panel.slice(m.at, marks[i + 1]?.at ?? panel.length);
    const rows = rowsIn(body);
    if (rows.length && m.name !== "SettingsPanel") components[m.name] = rows;
  });
}

let tab = null, sec = null;
const start = lines.findIndex((l) => l.startsWith("export function SettingsPanel"));
for (let i = start; i < lines.length; i++) {
  const line = lines[i];
  const tm = line.match(/\{tab === "([\w-]+)"/);
  if (tm) { tab = tm[1]; sec = null; }
  const sm = line.match(/SectionAnchor id="([\w-]+)"/) || line.match(/id="set-sec-([\w-]+)"/);
  if (sm) sec = sm[1];
  if (!tab) continue;
  const lm = line.match(/<SectionLabel[^>]*>\{t\("([^"]+)"\)/);
  if (lm) add({ k: lm[1], tab, sec: sec || undefined, s: 1 });
  for (const [name, rows] of Object.entries(components)) {
    if (line.includes(`<${name}`)) rows.forEach((r) => add({ ...r, tab, sec: sec || undefined }));
  }
  if (line.includes("<SettingRow")) {
    let chunk = line;
    for (let j = i + 1; j < Math.min(lines.length, i + 8) && !lines[j].includes("<SettingRow"); j++) chunk += "\n" + lines[j];
    rowsIn(chunk).forEach((r) => add({ ...r, tab, sec: sec || undefined }));
  }
}

// ── tabs that live in their own files ──
for (const [file, t, s] of [
  ["src/settings/account-tab.jsx", "account"],
  ["src/settings/storage-tab.jsx", "storage"],
  ["src/settings/composer-section.jsx", "lyrics", "lyrics-composer"],
]) rowsIn(read(file)).forEach((r) => add({ ...r, tab: t, sec: s }));

// ── tabs and sections themselves, from the settings sidebar ──
const nav = read("src/settings/sidebar-nav.jsx");
let curTab = null;
for (const line of nav.split("\n")) {
  const m = line.match(/^(\s*)\{ id: "([\w-]+)",\s+label: (?:t\("([^"]+)"\)|"([^"]+)")/);
  if (!m) continue;
  const [, indent, id, key, lit] = m;
  if (indent.length <= 4) { curTab = id; add({ k: key || lit, lit: lit ? 1 : undefined, tab: id, s: 2 }); }
  else add({ k: key || lit, lit: lit ? 1 : undefined, tab: curTab, sec: id, s: 1 });
}

// One entry per label and place.
const seen = new Set();
const unique = entries.filter((e) => {
  const id = `${e.k}|${e.tab}|${e.sec || ""}`;
  if (seen.has(id)) return false;
  seen.add(id);
  return true;
});

writeFileSync(join(root, "src/settings/search-index.js"),
  "// Generated by scripts/settings-index.mjs before every build. Do not edit by hand.\n" +
  "// k: label key (or literal text when lit), d: description key, tab/sec: where it lives,\n" +
  "// s: 1 = a section, 2 = a whole tab.\n" +
  `export const SETTINGS_INDEX = ${JSON.stringify(unique)};\n`);
console.log(`[settings-index] ${unique.length} entries`);
